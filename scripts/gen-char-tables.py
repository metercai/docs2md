#!/usr/bin/env python3
"""Generate the Unicode character tables the Rust port (order.rs) uses in
place of unicode crates (not in the offline cargo cache):

  WF    — codepoints with unicodedata.east_asian_width in "WF"
          (display_len: wide/fullwidth count two cells)
  DIGIT — codepoints where str.isdigit() is true
          (Python isdigit = Nd + No-with-Numeric_Type=Digit; differs from
          Rust char::is_numeric on Roman numerals and fractions)
  UPPER — codepoints where str.isupper() is true
          (Lu + Lt; differs from Rust char::is_uppercase on titlecase)
  ALPHA — codepoints where str.isalpha() is true
          (markdown.rs join_lines: hyphen-join guard)
  LOWER — codepoints where str.islower() is true
          (markdown.rs join_lines: hyphen-join guard)
  RTL   — codepoints with unicodedata.bidirectional in "R","AL"
          (rtl.py: right-to-left strong)
  LTRD  — codepoints with unicodedata.bidirectional in "L","EN","AN"
          (rtl.py: left-to-right strong, digits read LTR inside RTL)
  LONLY — codepoints with unicodedata.bidirectional == "L" exactly
          (rtl.py rtl_base / brackets_as_shapes: LTR letters only)
  COMB  — codepoints with unicodedata.category in "Mn","Me"
          (rtl.py: combining marks cluster after their base)
  NFKC  — presentation-form codepoints (0xFB1D-0xFDFF, 0xFE70-0xFEFF)
          whose unicodedata NFKC differs from the identity: (cp, str) pairs
          (rtl.py normalize: glyph variants -> base letters)

Each table is the sorted list of (start, end) runs; Rust binary-searches.
The predicates are taken from the product interpreter itself (the same
unicodedata the product's order_post.py uses), so they match bit-for-bit.

Output: <out-dir>/char_tables.rs

    <indra-ocr-venv>/python gen-char-tables.py <out-dir>
"""
import sys


def runs_of(pred):
    runs = []
    start = None
    for cp in range(0x110000):
        if pred(chr(cp)):
            if start is None:
                start = cp
        elif start is not None:
            runs.append((start, cp - 1))
            start = None
    if start is not None:
        runs.append((start, 0x10FFFF))
    return runs


def emit(name, runs):
    lines = [f"pub const {name}: &[(u32, u32)] = &[", ]
    for (s, e) in runs:
        lines.append(f"    (0x{s:X}, 0x{e:X}),")
    lines.append("];")
    return lines


def main():
    import unicodedata

    out_dir = sys.argv[1]
    tables = {
        "EAW_WF_RUNS": runs_of(lambda c: unicodedata.east_asian_width(c) in "WF"),
        "DIGIT_RUNS": runs_of(lambda c: c.isdigit()),
        "UPPER_RUNS": runs_of(lambda c: c.isupper()),
        "ALPHA_RUNS": runs_of(lambda c: c.isalpha()),
        "LOWER_RUNS": runs_of(lambda c: c.islower()),
        "RTL_RUNS": runs_of(lambda c: unicodedata.bidirectional(c) in ("R", "AL")),
        "LTRD_RUNS": runs_of(lambda c: unicodedata.bidirectional(c) in ("L", "EN", "AN")),
        "LONLY_RUNS": runs_of(lambda c: unicodedata.bidirectional(c) == "L"),
        "COMB_RUNS": runs_of(lambda c: unicodedata.category(c) in ("Mn", "Me")),
    }
    # Presentation forms that NFKC actually changes (within the two ranges
    # rtl.py treats as presentation forms); (cp, replacement) pairs.
    nfkc = []
    for cp in list(range(0xFB1D, 0xFDFF + 1)) + list(range(0xFE70, 0xFEFF + 1)):
        c = chr(cp)
        n = unicodedata.normalize("NFKC", c)
        if n != c:
            nfkc.append((cp, n))
    body = [
        "// Generated by scripts/gen-char-tables.py from the product interpreter",
        "// (indra_ocr venv): unicodedata.east_asian_width, str.isdigit, str.isupper,",
        "// str.isalpha, str.islower, unicodedata.bidirectional, unicodedata.category,",
        "// unicodedata.normalize NFKC (presentation forms).",
        "// Do not edit by hand.",
    ]
    for name, runs in tables.items():
        n = sum(e - s + 1 for s, e in runs)
        print(f"{name}: {len(runs)} runs, {n} codepoints", file=sys.stderr)
        body.append("")
        body.extend(emit(name, runs))
    print(f"NFKC_MAP: {len(nfkc)} pairs", file=sys.stderr)
    body.append("")
    body.append("pub const NFKC_MAP: &[(u32, &str)] = &[")
    for cp, n in nfkc:
        esc = n.replace("\\", "\\\\").replace('"', '\\"')
        body.append(f'    (0x{cp:X}, "{esc}"),')
    body.append("];")
    path = f"{out_dir}/char_tables.rs"
    with open(path, "w") as f:
        f.write("\n".join(body) + "\n")
    print(path)


if __name__ == "__main__":
    main()
